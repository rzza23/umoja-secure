package com.umoja.secure.crypto

import org.json.JSONObject
import java.util.Base64

/**
 * Provisioning bundle — the QR payload an enrolling device displays and
 * the admin app scans.
 *
 * Wire format (owner ruling, 2026-10-14):
 *
 *   {
 *     "domain": "umoja.enrollment-request.v1",
 *     "device_id": "<string>",
 *     "pub_device_auth_key": "<base64url 32B>",
 *     "pub_messaging_identity_key": "<base64url 32B>",
 *     "pub_wipe_confirmation_key": "<base64url 32B>"
 *   }
 *
 * This payload is NOT JCS-canonicalized and NOT signed in Phase 1. The
 * `domain` field is documentation today; it becomes load-bearing only
 * if the payload is ever signed by the device auth key in a future
 * hardening task.
 *
 * `device_id` is a public identifier generated by the enrolling device
 * — not the admin, not the backend — and is not derived from key
 * material. It appears in every authenticated request. Showing it in a
 * QR leaks nothing.
 *
 * Task: TASK-P1-025
 * ADR:  §6 step 5
 */
data class ProvisioningBundle(
    val deviceId: String,
    val pubDeviceAuthKey: String,
    val pubMessagingIdentityKey: String,
    val pubWipeConfirmationKey: String,
) {
    companion object {
        const val DOMAIN: String = "umoja.enrollment-request.v1"

        /** Parse from a raw QR-payload JSON string. */
        fun parse(json: String): ProvisioningBundle {
            val obj = try {
                JSONObject(json)
            } catch (e: Exception) {
                throw IllegalArgumentException("ProvisioningBundle: not valid JSON", e)
            }
            val map = linkedMapOf<String, Any?>()
            val keys = obj.keys()
            while (keys.hasNext()) {
                val k = keys.next()
                val v = obj.get(k)
                map[k] = if (v == JSONObject.NULL) null else v
            }
            return fromJsonMap(map)
        }

        /**
         * Parse from a JSON-decoded map. Runs content checks parallel to
         * AuthorizationMatrix.fromJsonMap's.
         */
        fun fromJsonMap(m: Map<String, Any?>): ProvisioningBundle {
            val expected = setOf(
                "domain",
                "device_id",
                "pub_device_auth_key",
                "pub_messaging_identity_key",
                "pub_wipe_confirmation_key",
            )
            val unexpected = m.keys - expected
            if (unexpected.isNotEmpty()) {
                throw IllegalArgumentException(
                    "unexpected field(s): ${unexpected.sorted().joinToString(", ")}",
                )
            }

            val domain = m["domain"]
            require(domain == DOMAIN) {
                "domain: expected \"$DOMAIN\", got ${domain?.let { "\"$it\"" } ?: "null"}"
            }
            val deviceId = requirePrintableAscii(m["device_id"], "device_id", MAX_DEVICE_ID_LEN)
            val pubDeviceAuthKey = requireBase64Url32(m["pub_device_auth_key"], "pub_device_auth_key")
            val pubMessagingIdentityKey = requireBase64Url32(
                m["pub_messaging_identity_key"], "pub_messaging_identity_key",
            )
            val pubWipeConfirmationKey = requireBase64Url32(
                m["pub_wipe_confirmation_key"], "pub_wipe_confirmation_key",
            )
            return ProvisioningBundle(
                deviceId = deviceId,
                pubDeviceAuthKey = pubDeviceAuthKey,
                pubMessagingIdentityKey = pubMessagingIdentityKey,
                pubWipeConfirmationKey = pubWipeConfirmationKey,
            )
        }

        private const val MAX_DEVICE_ID_LEN = 64
    }
}

// ---------- validation helpers ----------

private val PRINTABLE_ASCII_RE = Regex("^[\\x20-\\x7E]+$")

private fun requirePrintableAscii(value: Any?, field: String, maxLen: Int): String {
    val s = requireString(value, field)
    if (!PRINTABLE_ASCII_RE.matches(s)) {
        throw IllegalArgumentException("$field: must be printable ASCII")
    }
    if (s.length > maxLen) {
        throw IllegalArgumentException("$field: exceeds max length $maxLen, got ${s.length}")
    }
    return s
}
